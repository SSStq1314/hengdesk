-- M1 第二块 PR3b（D-37）：告警发送状态入库、用量未知标记。
-- Create "budget_alert_states" table
CREATE TABLE "budget_alert_states" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "org_id" bigint NOT NULL, "budget_id" bigint NOT NULL, "period_key" character varying NOT NULL, "level" bigint NOT NULL, "used" bigint NOT NULL DEFAULT 0, "created_at" timestamptz NOT NULL, PRIMARY KEY ("id"));
-- Create index "budgetalertstate_budget_id_period_key_level" to table: "budget_alert_states"
CREATE UNIQUE INDEX "budgetalertstate_budget_id_period_key_level" ON "budget_alert_states" ("budget_id", "period_key", "level");
-- Modify "usage_records" table
ALTER TABLE "usage_records" ADD COLUMN "usage_unknown" boolean NOT NULL DEFAULT false;
-- 历史记录：失败且 token 为 0 的视为用量未知
UPDATE "usage_records" SET "usage_unknown" = true WHERE "status" = 'error' AND "total_tokens" = 0;
-- 回填告警发送状态：旧版提醒的 dedupe_key 为 budget:<预算>:<更新时间毫秒>:<周期>:<档位>，只取与预算当前版本一致的，避免升级后重发
INSERT INTO "budget_alert_states" ("org_id", "budget_id", "period_key", "level", "used", "created_at")
SELECT DISTINCT ON (b."id", split_part(n."dedupe_key", ':', 4), split_part(n."dedupe_key", ':', 5))
       b."org_id", b."id", split_part(n."dedupe_key", ':', 4), split_part(n."dedupe_key", ':', 5)::bigint, 0, n."created_at"
FROM "notifications" n
JOIN "budgets" b ON b."id"::text = split_part(n."dedupe_key", ':', 2)
WHERE n."kind" = 'budget_alert' AND n."dedupe_key" ~ '^budget:[0-9]+:[0-9]+:[0-9]+:[0-9]+$'
  AND split_part(n."dedupe_key", ':', 3) = (floor(extract(epoch FROM b."updated_at") * 1000))::bigint::text
ORDER BY b."id", split_part(n."dedupe_key", ':', 4), split_part(n."dedupe_key", ':', 5), n."created_at"
ON CONFLICT DO NOTHING;
