-- M1 授权层数据迁移（手工补充，须在删除 is_super_admin 列之前执行）。
-- 1) 内置角色改名：admin→org_admin，auditor→security_auditor；权限明细由服务启动时 SyncBuiltinRoles 覆盖。
UPDATE "roles" SET "key" = 'org_admin', "name" = '组织管理员' WHERE "key" = 'admin' AND NOT EXISTS (SELECT 1 FROM "roles" WHERE "key" = 'org_admin');
UPDATE "roles" SET "key" = 'security_auditor', "name" = '安全审计员' WHERE "key" = 'auditor' AND NOT EXISTS (SELECT 1 FROM "roles" WHERE "key" = 'security_auditor');
-- 2) 审批人角色并入后续审批流配置，删除其成员关系与角色本身。
DELETE FROM "memberships" WHERE "role_id" IN (SELECT "id" FROM "roles" WHERE "key" = 'approver');
DELETE FROM "roles" WHERE "key" = 'approver';
-- 3) 补齐新内置角色占位行。
INSERT INTO "roles" ("created_at", "updated_at", "key", "name", "permissions", "builtin")
SELECT now(), now(), v.k, v.n, '[]'::jsonb, true
FROM (VALUES ('super_admin', '超级管理员'), ('security_auditor', '安全审计员'), ('org_admin', '组织管理员'), ('dept_admin', '部门管理员'), ('member', '成员')) AS v(k, n)
WHERE NOT EXISTS (SELECT 1 FROM "roles" r WHERE r."key" = v.k);
-- 4) is_super_admin=true 的用户转为 super_admin 角色成员关系。
INSERT INTO "memberships" ("created_at", "updated_at", "is_primary", "role_id", "user_id")
SELECT now(), now(), false, r."id", u."id" FROM "users" u CROSS JOIN "roles" r
WHERE u."is_super_admin" AND r."key" = 'super_admin'
  AND NOT EXISTS (SELECT 1 FROM "memberships" m WHERE m."user_id" = u."id" AND m."role_id" = r."id");
-- Modify "users" table
ALTER TABLE "users" DROP COLUMN "is_super_admin";
-- Create "acl" table
CREATE TABLE "acl" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "org_id" bigint NOT NULL, "resource_type" character varying NOT NULL, "resource_id" character varying NOT NULL, "subject_type" character varying NOT NULL, "subject_id" bigint NOT NULL, "include_children" boolean NOT NULL DEFAULT false, "perms" bigint NOT NULL, "created_by" bigint NULL, "created_at" timestamptz NOT NULL, PRIMARY KEY ("id"));
-- Create index "acl_org_id_resource_type_subject_type_subject_id" to table: "acl"
CREATE INDEX "acl_org_id_resource_type_subject_type_subject_id" ON "acl" ("org_id", "resource_type", "subject_type", "subject_id");
-- Create index "acl_resource_type_resource_id_subject_type_subject_id" to table: "acl"
CREATE UNIQUE INDEX "acl_resource_type_resource_id_subject_type_subject_id" ON "acl" ("resource_type", "resource_id", "subject_type", "subject_id");
-- Create "dept_closure" table
CREATE TABLE "dept_closure" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "org_id" bigint NOT NULL, "ancestor_id" bigint NOT NULL, "descendant_id" bigint NOT NULL, "depth" bigint NOT NULL, PRIMARY KEY ("id"));
-- Create index "deptclosure_ancestor_id_descendant_id" to table: "dept_closure"
CREATE UNIQUE INDEX "deptclosure_ancestor_id_descendant_id" ON "dept_closure" ("ancestor_id", "descendant_id");
-- Create index "deptclosure_descendant_id" to table: "dept_closure"
CREATE INDEX "deptclosure_descendant_id" ON "dept_closure" ("descendant_id");

-- 5) 为已有部门回填闭包表。
WITH RECURSIVE t ("org_id", "ancestor_id", "descendant_id", "depth") AS (
  SELECT "org_id", "id", "id", 0 FROM "departments"
  UNION ALL
  SELECT t."org_id", t."ancestor_id", d."id", t."depth" + 1 FROM t JOIN "departments" d ON d."parent_id" = t."descendant_id"
)
INSERT INTO "dept_closure" ("org_id", "ancestor_id", "descendant_id", "depth") SELECT "org_id", "ancestor_id", "descendant_id", "depth" FROM t;
